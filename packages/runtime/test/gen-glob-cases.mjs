const make = (tokens, max) => {
  const n = 1 + Math.floor(random() * max);
  let s = "";
  for (let i = 0; i < n; i++) s += pick(tokens);
  return s;
};
// A zero step never ends: Node's expansion fails with RangeError (slowly).
const fuzz = [["0", "{0..1..0}"]];
for (let i = 0; i < 3000; i++) fuzz.push([make(pathTokens, 6), make(patternTokens, 7)]);
for (const [path, pattern] of fuzz) {
  const results = [false, true].map((windows) => answers(path, pattern, windows));
  lines.push(`f\t${escape(path)}\t${escape(pattern)}\t${results.join("\t")}`);
}

