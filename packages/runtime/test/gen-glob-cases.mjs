// Generates path.matchesGlob test cases with Node as the oracle.
//
//   node --expose-internals gen-glob-cases.mjs > glob-cases.txt
//
// Lines are tab-separated:
//   p <path>                            adds a path to the curated list
//   c <pattern> <posix> <win32>         a pattern against every curated path
//   f <path> <pattern> <posix> <win32>  one fuzz case
// Strings keep printable ASCII and spell everything else (and "\") as
// \uXXXX UTF-16 code units, so lone surrogates survive. Each answer is two
// characters per path, case-sensitive then case-insensitive ("1", "0", or
// "E" when Node throws): Node 24 matches case-insensitively on macOS and
// Windows hosts, so both modes are recorded through the bundled minimatch
// with matchGlobPattern's exact options. Node v24 is required: the cases pin
// its bundled minimatch.
import { posix, win32 } from "node:path";
import { stdout } from "node:process";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { minimatch } = require("internal/deps/minimatch/index");

// The pattern has no u flag, so each match is one UTF-16 code unit.
const escape = (s) =>
  s.replace(/[^\x20-\x5b\x5d-\x7e]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0"));
const options = (windows, nocase) => ({
  nocase,
  windowsPathsNoEscape: true,
  nonegate: true,
  nocomment: true,
  optimizationLevel: 2,
  platform: windows ? "win32" : "posix",
  nocaseMagicOnly: true,
});
const lines = [];
const answer = (path, pattern, windows, nocase) => {
  try {
    return minimatch(path, pattern, options(windows, nocase)) ? "1" : "0";
  } catch {
    return "E";
  }
};
const hostNocase = process.platform === "darwin" || process.platform === "win32";
// Both case modes for one family; the public API on this host must agree
// with the recorded options.
const answers = (path, pattern, windows) => {
  const expected = [false, true].map((nocase) => answer(path, pattern, windows, nocase));
  let actual;
  try {
    actual = (windows ? win32 : posix).matchesGlob(path, pattern) ? "1" : "0";
  } catch {
    actual = "E";
  }
  if (actual !== expected[hostNocase ? 1 : 0])
    throw new Error(`oracle mismatch: ${path} ${pattern}`);
  return expected.join("");
};

