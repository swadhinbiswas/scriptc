// Generates node:url legacy-API and domain test cases with Node as the
// oracle.
//
//   node gen-url-legacy-cases.mjs > url-legacy-cases.txt
//
// Lines are tab-separated:
//   a <domain> <url.domainToASCII(domain)>
//   u <domain> <url.domainToUnicode(domain)>
//   p <flags> <input> <JSON of url.parse(input, flags & 1, flags & 2)>
//   f <input> <url.format(input)>
//   o <JSON object> <url.format(object)>
//   r <from> <to> <url.resolve(from, to)>
// A throwing call answers "E:" and the error's code (or name). Strings keep
// printable ASCII and spell everything else (and "\") as \uXXXX UTF-16 code
// units, so lone surrogates survive. Node v24 is required.
import url from "node:url";
import { stdout } from "node:process";

process.noDeprecation = true;

const escape = (s) =>
  s.replace(/[^\x20-\x5b\x5d-\x7e]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0"));
const attempt = (f) => {
  try {
    return f();
  } catch (e) {
    return `E:${e.code ?? e.name}`;
  }
};
const lines = [];
const seen = new Set();
const emit = (...fields) => {
  const line = fields.map(escape).join("\t");
  if (seen.has(line)) return;
  seen.add(line);
  lines.push(line);
};
const domain = (d) => {
  emit(
    "a",
    d,
    attempt(() => url.domainToASCII(d)),
  );
  emit(
    "u",
    d,
    attempt(() => url.domainToUnicode(d)),
  );
};
const parse = (input) => {
  for (const flags of [0, 1, 2, 3])
    emit(
      "p",
      String(flags),
      input,
      attempt(() => JSON.stringify(url.parse(input, (flags & 1) !== 0, (flags & 2) !== 0))),
    );
  emit(
    "f",
    input,
    attempt(() => url.format(input)),
  );
};
const resolve = (from, to) =>
  emit(
    "r",
    from,
    to,
    attempt(() => url.resolve(from, to)),
  );
const format = (object) =>
  emit(
    "o",
    JSON.stringify(object),
    attempt(() => url.format(object)),
  );

