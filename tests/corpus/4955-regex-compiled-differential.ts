function show(m: RegExpExecArray | null): string {
  if (m === null) return "-";
  const parts: string[] = [];
  for (let i = 0; i < m.length; i++) parts.push(m[i] === undefined ? "U" : JSON.stringify(m[i]));
  return `${m.index}:${parts.join(",")}`;
}

